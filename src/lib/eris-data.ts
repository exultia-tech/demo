export interface CompileErisOptions {
  os?: string;
  selectedModuleIds?: string[];
  autoRollbackMinutes?: number;
  includeTeardownScript?: boolean;
}

/**
 * Compiles a comprehensive bash shell script that intentionally injects the selected
 * vulnerable configurations into the endpoint, with an obvious warning banner and rollback function.
 */
export function compileErisChaosScript(
  optionsOrOs?: string | CompileErisOptions,
  selectedModuleIdsParam?: string[],
  autoRollbackMinutesParam?: number
): {
  script: string;
  activeModules: ErisModule[];
  rollbackCommand: string;
} {
  let os = 'ubuntu';
  let selectedModuleIds: string[] | undefined;
  let autoRollbackMinutes = 30;

  if (typeof optionsOrOs === 'object' && optionsOrOs !== null) {
    os = optionsOrOs.os || 'ubuntu';
    selectedModuleIds = optionsOrOs.selectedModuleIds;
    autoRollbackMinutes = optionsOrOs.autoRollbackMinutes !== undefined ? optionsOrOs.autoRollbackMinutes : 30;
  } else if (typeof optionsOrOs === 'string') {
    os = optionsOrOs;
    selectedModuleIds = selectedModuleIdsParam;
    if (autoRollbackMinutesParam !== undefined) autoRollbackMinutes = autoRollbackMinutesParam;
  }

  const effectiveModuleIds = selectedModuleIds !== undefined
    ? selectedModuleIds
    : ERIS_MODULES.filter(m => m.defaultEnabled).map(m => m.id);
  const activeModules = ERIS_MODULES.filter(m => effectiveModuleIds.includes(m.id));
  const lines: string[] = [];

  lines.push(`#!/usr/bin/env bash`);
  lines.push(`# ============================================================`);
  lines.push(`# EXULTIA ERIS: CONTROLLED VULNERABILITY INOCULATION SCRIPT`);
  lines.push(`# Named for Eris, Goddess of Chaos & Strife`);
  lines.push(`# ────────────────────────────────────────────────────────────`);
  lines.push(`# ⚠️ MANDATORY TESTING DISCLAIMER:`);
  lines.push(`# THIS SCRIPT DELIBERATELY INTRODUCES NON-COMPLIANT CONFIGURATIONS,`);
  lines.push(`# LISTENING SOCKETS, AND WEAKNESSES FOR REMEDIATION VALIDATION.`);
  lines.push(`# STRICTLY PROHIBITED IN PRODUCTION ENVIRONMENTS.`);
  lines.push(`# Generated: ${new Date().toISOString()} | Target OS: ${os}`);
  lines.push(`# Active Chaos Modules: ${activeModules.length}`);
  lines.push(`# ============================================================`);
  lines.push(``);
  lines.push(`log_warn() { printf '\\033[1;33m[ERIS CHAOS WARNING]\\033[0m %s\\n' "$1"; }`);
  lines.push(`log_info() { printf '\\033[1;36m[ERIS]\\033[0m %s\\n' "$1"; }`);
  lines.push(``);
  lines.push(`log_warn "Starting intentional vulnerability seeding for Praxis validation..."`);
  lines.push(``);

  // Snapshot directory setup
  lines.push(`# ── Safety Snapshot Directory ──────────────────────────────`);
  lines.push(`ERIS_DIR="/var/log/eris"`);
  lines.push(`mkdir -p "$ERIS_DIR/backup" 2>/dev/null || ERIS_DIR="/tmp/eris"`);
  lines.push(`mkdir -p "$ERIS_DIR/backup" 2>/dev/null || true`);
  lines.push(``);

  // Rollback function generation
  lines.push(`eris_rollback() {`);
  lines.push(`  log_info "Initiating instant rollback of all seeded Eris chaos vulnerabilities..."`);
  for (const mod of activeModules) {
    lines.push(`  # Rollback: ${mod.title}`);
    for (const cmd of mod.teardownCommands) {
      lines.push(`  ${cmd}`);
    }
  }
  lines.push(`  rm -f "$ERIS_DIR/eris-manifest.json" 2>/dev/null || true`);
  lines.push(`  log_info "✔ Rollback complete. Host restored to clean baseline state."`);
  lines.push(`}`);
  lines.push(``);
  lines.push(`if [ "$1" = "--rollback" ] || [ "$1" = "--revert" ] || [ "$1" = "clean" ]; then`);
  lines.push(`  eris_rollback`);
  lines.push(`  exit 0`);
  lines.push(`fi`);
  lines.push(``);

  // Execute inoculation commands for each module
  for (const mod of activeModules) {
    lines.push(`# ── Module: ${mod.id} (${mod.title}) ──`);
    lines.push(`# Severity: ${mod.severity} | CVSS: ${mod.cvss} | Ref: ${mod.cveRef || 'N/A'}`);
    lines.push(`log_warn "-> Inoculating: ${mod.title}..."`);
    for (const cmd of mod.setupCommands) {
      lines.push(`${cmd}`);
    }
    lines.push(``);
  }

  // Codify Eris Inoculation Manifest
  lines.push(`# ── Codify Inoculation Manifest for Praxis Detection ─────────`);
  lines.push(`cat << 'EOMANIFEST' > "$ERIS_DIR/eris-manifest.json"`);
  lines.push(JSON.stringify({
    generator: "Exultia Eris Chaos Engine v1.0",
    inoculatedAt: new Date().toISOString(),
    targetOs: os,
    activeModules: activeModules.map(m => ({
      id: m.id,
      title: m.title,
      severity: m.severity,
      cvss: m.cvss,
      praxisClass: m.praxisRemediationClass
    })),
    disclaimer: ERIS_MANDATORY_DISCLAIMER.shortWarning
  }, null, 2));
  lines.push(`EOMANIFEST`);
  lines.push(``);

  // Self-contained executable setup script saved on host for manual or cron rollback
  lines.push(`# ── Store Executable Script Locally for Rollback ───────────`);
  lines.push(`cp "$0" "$ERIS_DIR/eris-setup.sh" 2>/dev/null || true`);
  lines.push(`chmod +x "$ERIS_DIR/eris-setup.sh" 2>/dev/null || true`);
  lines.push(``);

  // Optional automatic safety rollback timer via at or sleep
  if (autoRollbackMinutes > 0) {
    lines.push(`# ── Automatic Failsafe Rollback Timer (${autoRollbackMinutes} minutes) ──`);
    lines.push(`if command -v at >/dev/null 2>&1; then`);
    lines.push(`  echo "$ERIS_DIR/eris-setup.sh --rollback" | at now + ${autoRollbackMinutes} minutes 2>/dev/null || true`);
    lines.push(`  log_info "Scheduled failsafe rollback in ${autoRollbackMinutes} minutes via 'at'."`);
    lines.push(`else`);
    lines.push(`  (sleep ${autoRollbackMinutes * 60} && "$ERIS_DIR/eris-setup.sh" --rollback) >/dev/null 2>&1 &`);
    lines.push(`  log_info "Spawned background failsafe timer: host will auto-revert in ${autoRollbackMinutes} minutes."`);
    lines.push(`fi`);
    lines.push(``);
  }

  lines.push(`log_info "============================================================"`);
  lines.push(`log_info "✔ Eris Chaos Inoculation Complete: ${activeModules.length} vulnerabilities active."`);
  lines.push(`log_info "Open Praxis to execute autonomous detection and remediation:"`);
  lines.push(`log_info "  URL: https://exultia.tech/app/praxis?erisRemediate=true"`);
  lines.push(`log_info "Manual Rollback Command:"`);
  lines.push(`log_info "  $ERIS_DIR/eris-setup.sh --rollback"`);
  lines.push(`log_info "============================================================"`);

  const compiledScript = lines.join('\n');
  return {
    script: compiledScript,
    activeModules,
    rollbackCommand: '/var/log/eris/eris-setup.sh --rollback'
  };
}

