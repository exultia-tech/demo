export interface CompileCrucibleOptions {
  os?: string;
  selectedModuleIds?: string[];
  autoRollbackMinutes?: number;
  includeTeardownScript?: boolean;
}

/**
 * Compiles a comprehensive bash shell script that intentionally injects the selected
 * vulnerable configurations into the endpoint, with an obvious warning banner and rollback function.
 */
export function compileCrucibleChaosScript(
  optionsOrOs?: string | CompileCrucibleOptions,
  selectedModuleIdsParam?: string[],
  autoRollbackMinutesParam?: number
): {
  script: string;
  activeModules: CrucibleModule[];
  rollbackCommand: string;
} {
  let os = 'ubuntu';
  let selectedModuleIds: string[] | undefined;
  let autoRollbackMinutes = 30;

  if (typeof optionsOrOs === 'object' && optionsOrOs !== null) {
    os = optionsOrOs.os || 'ubuntu';
    selectedModuleIds = optionsOrOs.selectedModuleIds;
    autoRollbackMinutes = optionsOrOs.autoRollbackMinutes !== undefined ? optionsOrOs.autoRollbackMinutes : 30;
  } else if (typeof optionsOrOs === 'string') {
    os = optionsOrOs;
    selectedModuleIds = selectedModuleIdsParam;
    if (autoRollbackMinutesParam !== undefined) autoRollbackMinutes = autoRollbackMinutesParam;
  }

  const effectiveModuleIds = selectedModuleIds !== undefined
    ? selectedModuleIds
    : CRUCIBLE_MODULES.filter(m => m.defaultEnabled).map(m => m.id);
  const activeModules = CRUCIBLE_MODULES.filter(m => effectiveModuleIds.includes(m.id));
  const lines: string[] = [];

  lines.push(`#!/usr/bin/env bash`);
  lines.push(`# ============================================================`);
  lines.push(`# EXULTIA CRUCIBLE: CONTROLLED VULNERABILITY INOCULATION SCRIPT`);
  lines.push(`# ────────────────────────────────────────────────────────────`);
  lines.push(`# ⚠️ MANDATORY TESTING DISCLAIMER:`);
  lines.push(`# THIS SCRIPT DELIBERATELY INTRODUCES NON-COMPLIANT CONFIGURATIONS,`);
  lines.push(`# LISTENING SOCKETS, AND WEAKNESSES FOR REMEDIATION VALIDATION.`);
  lines.push(`# STRICTLY PROHIBITED IN PRODUCTION ENVIRONMENTS.`);
  lines.push(`# Generated: ${new Date().toISOString()} | Target OS: ${os}`);
  lines.push(`# Active Chaos Modules: ${activeModules.length}`);
  lines.push(`# ============================================================`);
  lines.push(``);
  lines.push(`log_warn() { printf '\\033[1;31m[CRUCIBLE WARNING]\\033[0m %s\\n' "$1"; }`);
  lines.push(`log_info() { printf '\\033[1;36m[CRUCIBLE]\\033[0m %s\\n' "$1"; }`);
  lines.push(``);
  lines.push(`log_warn "Starting intentional vulnerability seeding for Praxis validation..."`);
  lines.push(``);

  // Setup backup directory for safety
  lines.push(`# ── Safety Snapshot Directory ──────────────────────────────`);
  lines.push(`CRUCIBLE_DIR="/var/log/crucible"`);
  lines.push(`mkdir -p "$CRUCIBLE_DIR/backup" 2>/dev/null || CRUCIBLE_DIR="/tmp/crucible"`);
  lines.push(`mkdir -p "$CRUCIBLE_DIR/backup" 2>/dev/null || true`);
  lines.push(``);

  // Rollback function generation
  lines.push(`crucible_rollback() {`);
  lines.push(`  log_info "Initiating instant rollback of all seeded Crucible vulnerabilities..."`);
  for (const mod of activeModules) {
    lines.push(`  # Rollback: ${mod.title}`);
    for (const cmd of mod.teardownCommands) {
      lines.push(`  ${cmd}`);
    }
  }
  lines.push(`  rm -f "$CRUCIBLE_DIR/crucible-manifest.json" 2>/dev/null || true`);
  lines.push(`  log_info "✔ Rollback complete. Host restored to clean baseline state."`);
  lines.push(`}`);
  lines.push(``);
  lines.push(`if [ "$1" = "--rollback" ] || [ "$1" = "--revert" ] || [ "$1" = "clean" ]; then`);
  lines.push(`  crucible_rollback`);
  lines.push(`  exit 0`);
  lines.push(`fi`);
  lines.push(``);

  // Execute inoculation commands for each module
  for (const mod of activeModules) {
    lines.push(`# ── Module: ${mod.id} (${mod.title}) ──`);
    lines.push(`# Severity: ${mod.severity} | CVSS: ${mod.cvss} | Ref: ${mod.cveRef || 'N/A'}`);
    lines.push(`log_warn "-> Inoculating: ${mod.title}..."`);
    for (const cmd of mod.setupCommands) {
      lines.push(`${cmd}`);
    }
    lines.push(``);
  }

  // Codify Crucible Inoculation Manifest
  lines.push(`# ── Codify Inoculation Manifest for Praxis Detection ─────────`);
  lines.push(`cat << 'EOMANIFEST' > "$CRUCIBLE_DIR/crucible-manifest.json"`);
  lines.push(JSON.stringify({
    manifestType: 'Crucible-Chaos-Inoculation',
    version: '1.0',
    inoculatedAt: new Date().toISOString(),
    targetHost: os,
    seededModuleCount: activeModules.length,
    seededModules: activeModules.map(m => ({
      id: m.id,
      title: m.title,
      severity: m.severity,
      cvss: m.cvss,
      cveRef: m.cveRef,
      praxisRemediationClass: m.praxisRemediationClass
    })),
    status: 'ACTIVE_VULNERABILITIES_PRESENT',
    safetyNotice: 'Intentionally non-compliant test environment.'
  }, null, 2));
  lines.push(`EOMANIFEST`);
  lines.push(``);

  // Auto-rollback countdown reminder
  if (autoRollbackMinutes > 0) {
    lines.push(`# Optional Auto-Rollback Scheduler`);
    lines.push(`if command -v at >/dev/null 2>&1; then`);
    lines.push(`  echo "$0 --rollback" | at now + ${autoRollbackMinutes} minutes 2>/dev/null || true`);
    lines.push(`  log_info "Safety auto-rollback scheduled in ${autoRollbackMinutes} minutes via 'at'."`);
    lines.push(`fi`);
    lines.push(``);
  }

  lines.push(`log_warn "============================================================"`);
  lines.push(`log_warn "✔ Host successfully inoculated with ${activeModules.length} test vulnerabilities."`);
  lines.push(`log_warn "Next Step: Run Praxis remediation to neutralize these flaws and generate CBOM."`);
  lines.push(`log_info "To undo changes at any time, run: $0 --rollback"`);
  lines.push(`log_warn "============================================================"`);
  lines.push(``);

  return {
    script: lines.join('\n'),
    activeModules,
    rollbackCommand: `/var/log/crucible/crucible-setup.sh --rollback`
  };
}
